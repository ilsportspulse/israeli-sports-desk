#!/usr/bin/env node
// Re-edit the BODY of already-published English articles to a professional,
// naturally-varied, human broadsheet standard — breaking the old fixed-7
// -paragraph template WITHOUT a mechanical hack and WITHOUT touching facts.
//
// Hard guarantees enforced in the prompt AND validated after:
//   * every number, score, date, name, team and quote is preserved verbatim
//   * no new facts are invented; only structure, flow, rhythm and readability change
//   * paragraphs stay short and readable (never dense walls of text)
//   * length is flexible (5-18) and varies by story — never padded to a target
//
// Title, dek, facts and media are left untouched. When a body changes, updatedAt
// is bumped so stale FR/ES translations are dropped by the resolver and
// regenerated by scripts/translate-articles.mjs.
//
//   node scripts/humanize-articles.mjs                 # all published, newest first
//   HUMANIZE_MAX=3 node scripts/humanize-articles.mjs  # bounded batch
//   HUMANIZE_IDS=a,b node scripts/humanize-articles.mjs  # specific article ids

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ARTICLES = path.join(root, "data", "articles.json");

const MODEL = process.env.ANTHROPIC_MODEL ?? "claude-sonnet-5";
const MAX = Number(process.env.HUMANIZE_MAX ?? "0");
const ONLY = (process.env.HUMANIZE_IDS ?? "").split(",").map((s) => s.trim()).filter(Boolean);
const TIMEOUT_MS = Number(process.env.HUMANIZE_TIMEOUT_MS ?? String(6 * 60 * 1000));

// The CLI reuses the machine's logged-in Claude session; no env token required.
const apiKey = process.env.ANTHROPIC_API_KEY;
const MODE = process.env.HUMANIZE_MODE ?? (apiKey && !process.env.CLAUDE_CODE_OAUTH_TOKEN ? "api" : "cli");

let client = null;
if (MODE === "api") {
  const { default: Anthropic } = await import("@anthropic-ai/sdk");
  client = new Anthropic({ apiKey });
}

// Every standalone number token in the source must survive the rewrite. This is a
// blunt but effective guard against silent fact drift (dropped/changed figures).
function numberMultiset(text) {
  const nums = (text.match(/\d[\d.,]*/g) ?? []).map((n) => n.replace(/[.,]$/, ""));
  const map = new Map();
  for (const n of nums) map.set(n, (map.get(n) ?? 0) + 1);
  return map;
}

function numbersPreserved(before, after) {
  const a = numberMultiset(before);
  const b = numberMultiset(after);
  for (const [n, count] of a) {
    if ((b.get(n) ?? 0) < count) return `missing number "${n}"`;
  }
  return null;
}

function buildPrompt(article) {
  return `You are the copy desk of Israel Sports Pulse, an English-language quality sports newsroom. Re-edit the BODY of this published article so it reads like polished, professional, human broadsheet journalism.

ABSOLUTE RULES:
- Preserve EVERY fact exactly: names, teams, competitions, cities, scores, dates, ages, money, statistics and quotes. Do not add, drop, soften, round or invent anything. Same information in, same information out.
- Only improve structure, flow, sentence rhythm and readability. Re-paragraph naturally.
- NEVER a fixed 7-paragraph template. Let the material decide the number of paragraphs (between 5 and 18) — shorter if the story is small; do NOT pad or repeat to make it longer.
- Keep paragraphs short and readable (roughly 2-4 sentences). No dense walls of text that tire the reader.
- Keep it in English. Do not change the headline, standfirst or the facts list.

Article title (context, do not change): ${article.title}
Current body paragraphs (JSON array):
${JSON.stringify(article.body, null, 2)}`;
}

function extractJson(text) {
  if (!text) return null;
  const fenced = text.match(/```(?:json)?\s*([\s\S]*?)```/i);
  const candidates = [];
  if (fenced) candidates.push(fenced[1]);
  const first = text.indexOf("{");
  const last = text.lastIndexOf("}");
  if (first !== -1 && last > first) candidates.push(text.slice(first, last + 1));
  candidates.push(text);
  for (const raw of candidates) {
    try {
      return JSON.parse(raw.trim());
    } catch {
      /* next */
    }
  }
  return null;
}

function viaCli(article) {
  const prompt = `${buildPrompt(article)}

Return ONLY a raw JSON object: {"body": [array of 5-18 paragraph strings]}. No prose, no code fences.`;
  const out = execFileSync(
    "claude",
    ["-p", prompt, "--output-format", "json", "--model", MODEL, "--permission-mode", "default"],
    { cwd: root, encoding: "utf8", maxBuffer: 32 * 1024 * 1024, timeout: TIMEOUT_MS, env: { ...process.env } },
  );
  let resultText = out;
  try {
    const envelope = JSON.parse(out);
    resultText = envelope.result ?? envelope.text ?? out;
  } catch {
    /* raw */
  }
  return extractJson(resultText);
}

async function viaApi(article) {
  const schema = { type: "object", required: ["body"], properties: { body: { type: "array", items: { type: "string" }, minItems: 5, maxItems: 18 } } };
  const response = await client.messages.create({
    model: MODEL,
    max_tokens: 6000,
    tools: [{ name: "emit_body", description: "Emit the re-edited body.", input_schema: schema }],
    tool_choice: { type: "tool", name: "emit_body" },
    messages: [{ role: "user", content: `${buildPrompt(article)}\n\nReturn the re-edited body by calling emit_body.` }],
  });
  const toolUse = response.content.find((c) => c.type === "tool_use" && c.name === "emit_body");
  return toolUse ? toolUse.input : null;
}

function validBody(article, body) {
  if (!Array.isArray(body) || body.length < 5 || body.length > 18) return "bad length";
  if (body.some((p) => typeof p !== "string" || p.trim().length < 20)) return "empty/short paragraph";
  const joinedBefore = article.body.join(" ");
  const joinedAfter = body.join(" ");
  const numIssue = numbersPreserved(joinedBefore, joinedAfter);
  if (numIssue) return numIssue;
  // Guard against wholesale shrinkage (lost information): keep >=85% of the words.
  const wb = joinedBefore.split(/\s+/).length;
  const wa = joinedAfter.split(/\s+/).length;
  if (wa < wb * 0.85) return `too much text lost (${wa}/${wb} words)`;
  return null;
}

async function main() {
  const articles = JSON.parse(fs.readFileSync(ARTICLES, "utf8"));
  let targets = articles
    .filter((a) => a.status !== "review" && Array.isArray(a.body))
    .sort((a, b) => new Date(b.updatedAt ?? b.publishedAt).getTime() - new Date(a.updatedAt ?? a.publishedAt).getTime());
  if (ONLY.length) targets = targets.filter((a) => ONLY.includes(a.id));
  const batch = MAX > 0 ? targets.slice(0, MAX) : targets;

  const nowIso = new Date().toISOString();
  console.log(`Humanize: mode=${MODE}, model=${MODEL}, candidates=${targets.length}, this run=${batch.length}`);

  let done = 0;
  let skipped = 0;
  for (const article of batch) {
    try {
      const result = MODE === "cli" ? viaCli(article) : await viaApi(article);
      const body = result?.body;
      const issue = validBody(article, body);
      if (issue) {
        skipped += 1;
        console.log(`  ~ ${article.id} — kept original (${issue})`);
        continue;
      }
      const oldLen = article.body.length;
      article.body = body.map((p) => p.trim());
      article.updatedAt = nowIso; // revised copy: invalidates stale translations
      done += 1;
      // Persist after each success so a long run is crash-safe and resumable.
      fs.writeFileSync(ARTICLES, JSON.stringify(articles, null, 2) + "\n");
      console.log(`  ✓ ${article.id} — ${oldLen} -> ${body.length} paragraphs`);
    } catch (err) {
      skipped += 1;
      console.log(`  ✗ ${article.id} — ${err.message?.split("\n")[0] ?? err}`);
    }
  }

  console.log(`Humanize done — rewrote ${done}, kept ${skipped}.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
